import { defineDurable } from "@zapier/zapier-durable";
import { createZapierSdk } from "@zapier/zapier-sdk";
import { z } from "zod";

import {
  INVOICE_DOCUMENT_TYPE,
  EXPENSE_DOCUMENT_TYPE,
  DEFAULT_CUSTOMER_NAME,
  DEFAULT_VENDOR_NAME,
  BANK_ACCOUNT_ID,
  EXPENSE_ACCOUNT_ID,
  EXPENSE_PAYMENT_TYPE,
} from "./config.ts";

const sdk = createZapierSdk();

// Seconds to wait before searching QuickBooks, so upstream row edits settle. Use 0 to skip the wait.
const SETTLE_SECONDS = 120;

const OptionalText = z.string().nullable().optional();

const InputSchema = z
  .object({
    new: z
      .object({
        data: z
          .object({
            f1: OptionalText,
            f2: OptionalText,
            f3: z.union([z.string(), z.number()]).nullable().optional(),
            f4: OptionalText,
            f5: OptionalText,
            f6: OptionalText,
            f7: OptionalText,
            f8: OptionalText,
          })
          .loose(),
      })
      .loose(),
    record_id: OptionalText,
  })
  .loose();

const workflow = defineDurable(
  "create-invoices-and-expenses-from-new-table-rows",
  async (ctx, rawInput) => {
    const input = InputSchema.parse(
      typeof rawInput === "string" ? JSON.parse(rawInput) : rawInput,
    );
    const row = input.new.data;

    const documentNumber = (row.f1 ?? "").trim();
    const documentType = (row.f2 ?? "").trim().toLowerCase();
    const amount = Number(row.f3 ?? 0);
    const transactionDate = row.f4 ?? null;
    const lineDetails = row.f5 ?? "";
    const trackingReference = row.f6 ?? "";
    const counterpartyName = (row.f7 ?? "").trim();

    if (
      documentType !== INVOICE_DOCUMENT_TYPE &&
      documentType !== EXPENSE_DOCUMENT_TYPE
    ) {
      return {
        skipped: true,
        reason: "not-billable-document-type",
        documentType,
      };
    }

    if (SETTLE_SECONDS > 0) {
      await ctx.wait("wait-for-row-to-settle", SETTLE_SECONDS);
    }

    if (documentType === INVOICE_DOCUMENT_TYPE) {
      const existing = await ctx.step("find-existing-invoice", async () =>
        sdk.runAction({
          appKey: "quickbooks",
          actionType: "search",
          actionKey: "invoice",
          connection: "quickbooks",
          inputs: { number: documentNumber },
        }),
      );
      if (existing.data?.[0]) {
        return {
          skipped: true,
          reason: "invoice-already-exists",
          documentNumber,
        };
      }

      const customer = await ctx.step("find-customer", async () =>
        sdk.runAction({
          appKey: "quickbooks",
          actionType: "search",
          actionKey: "customer_v2",
          connection: "quickbooks",
          inputs: {
            search_field: "name",
            search_value: counterpartyName || DEFAULT_CUSTOMER_NAME,
          },
        }),
      );
      const customerId = (
        customer.data?.[0] as { id?: string | number } | undefined
      )?.id;
      if (!customerId) {
        return { skipped: true, reason: "customer-not-found", documentNumber };
      }

      const invoice = await ctx.step("create-quickbooks-invoice", async () =>
        sdk.runAction({
          appKey: "quickbooks",
          actionType: "write",
          actionKey: "new_invoice_v4",
          connection: "quickbooks",
          inputs: {
            customer: String(customerId),
            number: documentNumber,
            txn_date: transactionDate,
            tracking_number: trackingReference,
            line_description: lineDetails,
            line_amount: amount,
            line_item_qty: "1",
            isAutoGeneratedNumber: "false",
          },
        }),
      );

      return {
        created: "invoice",
        documentNumber,
        invoice: invoice.data?.[0] ?? null,
      };
    }

    const existing = await ctx.step("find-existing-expense", async () =>
      sdk.runAction({
        appKey: "quickbooks",
        actionType: "search",
        actionKey: "find_purchase_expense",
        connection: "quickbooks",
        inputs: { docNumber: documentNumber },
      }),
    );
    if (existing.data?.[0]) {
      return {
        skipped: true,
        reason: "expense-already-exists",
        documentNumber,
      };
    }

    const vendor = await ctx.step("find-vendor", async () =>
      sdk.runAction({
        appKey: "quickbooks",
        actionType: "search",
        actionKey: "vendor",
        connection: "quickbooks",
        inputs: { name: counterpartyName || DEFAULT_VENDOR_NAME },
      }),
    );
    const vendorId = (vendor.data?.[0] as { id?: string | number } | undefined)
      ?.id;
    if (!vendorId) {
      return { skipped: true, reason: "vendor-not-found", documentNumber };
    }

    const expense = await ctx.step("create-quickbooks-expense", async () =>
      sdk.runAction({
        appKey: "quickbooks",
        actionType: "write",
        actionKey: "expense",
        connection: "quickbooks",
        inputs: {
          payee_type: "Vendor",
          payee: String(vendorId),
          account: BANK_ACCOUNT_ID,
          payment_type: EXPENSE_PAYMENT_TYPE,
          date: transactionDate,
          reference_number: documentNumber,
          memo: trackingReference,
          account_details_account: EXPENSE_ACCOUNT_ID,
          account_details_amount: amount,
          account_details_description: lineDetails,
        },
      }),
    );

    return {
      created: "expense",
      documentNumber,
      expense: expense.data?.[0] ?? null,
    };
  },
);

export default workflow;
